"""帮助指令：/help 列出机器人全部指令、用法和注意事项。

独立插件，不依赖 chunithm_bot 包，保证即使分析插件加载失败也能查到指令。
帮助文本写成常量，改指令时同步这一处即可。
"""

from nonebot import on_command
from nonebot.adapters.onebot.v11 import Message

# 帮助文本集中维护：新增/修改指令时只改这一处。
HELP_TEXT = """中二节奏 · 底力分析
—————————————
【账号绑定】群聊 / 私聊都可以
/中二绑定 好友码
    绑定落雪玩家。好友码是 15 位数字，只做查询用，不会索要落雪密码。
/中二绑定确认
    确认 10 分钟内发起的绑定，超时需重新发起。
/中二绑定状态
    查看当前绑定的玩家名与 Rating。
/中二解绑
    解除绑定，同时清除待确认数据。

【成绩分析】群聊 / 私聊都可以
/底力分析
    读取落雪成绩并生成底力分析图片报告，包含：
    · 能力倾向统计（高物量 / 键盘谱 / 底力谱 / 体力谱 / 技巧谱 五维相对倾向雷达）
    · 配置标签统计（叠 / 切 / 技 / 乱 / 反手 / 布 / 交互 / 纵连 / 爆发 九维相对倾向雷达）
    · 难度标签统计（按谱面物量推算定数，标注诈称 / 差不多 / 水）
    · 亮点分析、数据边界与锐评总结（各难度档的「舒适区边界」会单独点名）
    别名：/中二底力分析、/chunithm底力分析

【其它】
/help  显示本帮助（别名：/帮助、/指令、/菜单）
/hello  连通性测试，能回复说明 QQ、NapCat、NoneBot 链路正常（别名：/你好）

—————————————
数据来源：落雪咖啡屋（LXNS）中二节奏 API，只代表已同步的 Best / Selection / New 成绩，不等同于完整游玩历史。
能力倾向与定数偏离由谱面物量构成推算，是相对参考值，不是官方数据。
配置维度同样由物量构成与 BPM 近似推断——落雪不提供逐键位置，叠 / 切 / 乱 这类排列层面的差异无法精确还原。

"""

help_command = on_command("help", aliases={"帮助", "指令", "菜单"}, priority=5, block=True)


@help_command.handle()
async def handle_help() -> None:
    # 帮助不含个人信息，群聊私聊都直接返回。
    await help_command.finish(Message(HELP_TEXT))
